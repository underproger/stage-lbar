# Генерация масок/рамок баннера услуг по точкам, снятым с макета (система 1920, баннер 1920×1040, фото — от x=890, y=142)
OX, OY = 890, 142
W, H = 1920 - OX, 1040 - OY   # 1030 × 898

def cr2bez(pts, closed=False):
    # Catmull-Rom → кубические Безье (tension 0.5)
    d = f"{pts[0][0]:.1f} {pts[0][1]:.1f}"
    out = []
    for i in range(len(pts) - 1):
        p0 = pts[i - 1] if i > 0 else pts[i]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[i + 2] if i + 2 < len(pts) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:.1f} {p2[1]:.1f}")
    return "M" + d + " ".join(out)

def loc(pts):
    return [(x - OX, y - OY) for x, y in pts]

